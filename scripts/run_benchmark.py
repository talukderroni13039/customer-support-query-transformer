EVAL_PATH = PROJECT_ROOT / "data" / "eval" / "conversations.json"
REPORT_PATH = PROJECT_ROOT / "docs" / "BENCHMARK.md"
RAW_RESULTS_PATH = PROJECT_ROOT / "data" / "cache" / "benchmark_results.json"
START_MARKER = "<!-- BENCHMARK:START (generated by scripts/run_benchmark.py; do not edit) -->"
END_MARKER = "<!-- BENCHMARK:END -->"
RANK_DEPTH = 10  # articles requested per search; MRR is computed over these
SMALL_TALK = "small_talk"
FOLLOW_UP_PATTERNS = ("pronoun", "ellipsis", "correction", "multi_reference")


@dataclass(frozen=True)
class BenchmarkConfig:
    number: int
    name: str
    query_mode: QueryMode
    retrieval: RetrievalMode
    rerank: bool


CONFIGS = [
    BenchmarkConfig(1, "Naive", QueryMode.QUESTION_ONLY, RetrievalMode.VECTOR, False),
    BenchmarkConfig(2, "Naive + history", QueryMode.FULL_HISTORY, RetrievalMode.VECTOR, False),
    BenchmarkConfig(3, "+ Rewrite", QueryMode.REWRITE, RetrievalMode.VECTOR, False),
    BenchmarkConfig(4, "+ Hybrid", QueryMode.REWRITE, RetrievalMode.HYBRID, False),
    BenchmarkConfig(5, "Full pipeline", QueryMode.REWRITE, RetrievalMode.HYBRID, True),
    BenchmarkConfig(6, "Keyword only (reference)", QueryMode.REWRITE, RetrievalMode.KEYWORD, False),
]


@dataclass(frozen=True)
class CaseResult:
    case_id: str
    pattern: str
    config: int
    search_query: str
    ranked_ids: list[str]
    expected_ids: list[str]
    needs_retrieval: bool
    rewrite_source: str
    rewrite_fallback: bool
    rerank_fallback: bool
    latency_ms: float


# --- metrics (pure functions) ----------------------------------------------------------------


def first_correct_rank(ranked_ids: list[str], expected_ids: list[str]) -> int | None:
    for rank, article_id in enumerate(ranked_ids, start=1):
        if article_id in expected_ids:
            return rank
    return None


def hit_at_k(results: list[CaseResult], k: int) -> float:
    """Share of cases with an expected article in the top k."""
    if not results:
        return 0.0
    hits = sum(
        1
        for r in results
        if (rank := first_correct_rank(r.ranked_ids, r.expected_ids)) is not None and rank <= k
    )
    return hits / len(results)


def mean_reciprocal_rank(results: list[CaseResult]) -> float:
    """Average of 1 / rank of the first correct article (0 when it is missing)."""
    if not results:
        return 0.0
    total = 0.0
    for r in results:
        rank = first_correct_rank(r.ranked_ids, r.expected_ids)
        total += 1.0 / rank if rank else 0.0
    return total / len(results)


def percentile(values: list[float], pct: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    index = max(math.ceil(pct / 100 * len(ordered)) - 1, 0)
    return ordered[index]


def small_talk_correct(results: list[CaseResult]) -> int:
    """A small-talk case is correct when the pipeline decided not to retrieve."""
    return sum(1 for r in results if not r.needs_retrieval)


# --- report ----------------------------------------------------------------------------------


def render_tables(results: list[CaseResult], meta: dict[str, Any]) -> str:
    by_config = {c.number: [r for r in results if r.config == c.number] for c in CONFIGS}
    patterns = list(dict.fromkeys(r.pattern for r in results))

    lines = [
        START_MARKER,
        "",
        f"Run: {meta['run_at']} · {meta['cases']} eval cases ({meta['retrieval_cases']} retrieval, "
        f"{meta['small_talk_cases']} small talk) · {meta['articles']} articles / {meta['chunks']} "
        f"chunks · embedder `{meta['embedding_model']}` · reranker `{meta['reranker_model']}` · "
        f"rewriter `{meta['rewrite_provider']}` · CPU.",
        "",
        f"Settings: `CANDIDATES_PER_RETRIEVER={meta['candidates']}`, `RRF_K={meta['rrf_k']}`, "
        f"`RERANK_CANDIDATES={meta['rerank_candidates']}`, "
        f"`RERANK_MIN_SCORE={meta['rerank_min_score']}`, "
        f"`MAX_HISTORY_MESSAGES={meta['max_history']}`.",
        "",
        f"Claude calls made by this run: {meta['llm_calls_this_run']} "
        f"(total for the build so far: {meta['llm_calls_total']} of {meta['llm_call_budget']}).",
        "",
        "## Configurations",
        "",
        "hit@1, hit@3 and MRR are over the retrieval cases; small talk is scored separately "
        "(correct = the pipeline decided not to retrieve). Latency is per search over all cases; "
        "for rewrites served from the cache, the latency of the original Claude call is added "
        "back.",
        "",
        "| # | Config | query_mode | retrieval | rerank | hit@1 | hit@3 | MRR | small talk "
        "| avg latency | p95 latency | rewrite fallbacks |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for config in CONFIGS:
        rows = by_config[config.number]
        retrieval_rows = [r for r in rows if r.pattern != SMALL_TALK]
        talk_rows = [r for r in rows if r.pattern == SMALL_TALK]
        latencies = [r.latency_ms for r in rows]
        name = f"**{config.name}**" if config.number in (1, 5) else config.name
        lines.append(
            f"| {config.number} | {name} | {config.query_mode.value} | {config.retrieval.value} "
            f"| {'yes' if config.rerank else 'no'} "
            f"| {hit_at_k(retrieval_rows, 1):.2f} | {hit_at_k(retrieval_rows, 3):.2f} "
            f"| {mean_reciprocal_rank(retrieval_rows):.3f} "
            f"| {small_talk_correct(talk_rows)}/{len(talk_rows)} "
            f"| {statistics.fmean(latencies):.0f} ms | {percentile(latencies, 95):.0f} ms "
            f"| {sum(1 for r in rows if r.rewrite_fallback)} |"
        )

    header = "| Pattern | cases | " + " | ".join(f"{c.number}. {c.name}" for c in CONFIGS) + " |"
    divider = "|---|---|" + "---|" * len(CONFIGS)
    for title, cell in (
        ("hit@1 per pattern", lambda rows: f"{hit_at_k(rows, 1):.2f}"),
        ("MRR per pattern", lambda rows: f"{mean_reciprocal_rank(rows):.2f}"),
    ):
        lines += ["", f"## {title}", "", header, divider]
        for pattern in patterns:
            if pattern == SMALL_TALK:
                continue
            cells = [
                cell([r for r in by_config[c.number] if r.pattern == pattern]) for c in CONFIGS
            ]
            count = sum(1 for r in by_config[1] if r.pattern == pattern)
            lines.append(f"| `{pattern}` | {count} | " + " | ".join(cells) + " |")
        follow_up = [
            cell([r for r in by_config[c.number] if r.pattern in FOLLOW_UP_PATTERNS])
            for c in CONFIGS
        ]
        count = sum(1 for r in by_config[1] if r.pattern in FOLLOW_UP_PATTERNS)
        lines.append(f"| *all follow-ups* | {count} | " + " | ".join(follow_up) + " |")

    lines += ["", END_MARKER]
    return "\n".join(lines)


def write_report(tables: str) -> None:
    if REPORT_PATH.exists():
        existing = REPORT_PATH.read_text(encoding="utf-8")
        if START_MARKER in existing and END_MARKER in existing:
            before = existing.split(START_MARKER)[0]
            after = existing.split(END_MARKER, 1)[1]
            REPORT_PATH.write_text(before + tables + after, encoding="utf-8", newline="\n")
            return
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(
        "# Benchmark\n\nPipeline stages compared on `data/eval/conversations.json`. "
        "Regenerate with `uv run python -m scripts.run_benchmark`.\n\n"
        + tables
        + "\n\n## Findings\n\n_To be written from the tables above._\n",
        encoding="utf-8",
        newline="\n",
    )


# --- run -------------------------------------------------------------------------------------


async def run_config(
    config: BenchmarkConfig,
    cases: list[dict[str, Any]],
    service: SupportSearchService,
    query_service: QueryService,
    rewriter: Any,
) -> list[CaseResult]:
    results: list[CaseResult] = []
    for case in cases:
        request = SearchRequest(
            question=case["question"],
            history=case["history"],
            top_k=RANK_DEPTH,
            query_mode=config.query_mode,
            retrieval=config.retrieval,
            rerank=config.rerank,
        )
        started = time.perf_counter()
        outcome = await service.search(request)
        latency_ms = (time.perf_counter() - started) * 1000
        if outcome.rewrite_source == "cache" and isinstance(rewriter, CachedRewriter):
            # Report what a real request costs: add the original Claude call back.
            recent = query_service.recent_history(request.history)
            latency_ms += rewriter.cached_latency_ms(request.question, recent) or 0.0
        results.append(
            CaseResult(
                case_id=case["id"],
                pattern=case["pattern"],
                config=config.number,
                search_query=outcome.search_query,
                ranked_ids=[r.article_id for r in outcome.results],
                expected_ids=case["expected_article_ids"],
                needs_retrieval=outcome.needs_retrieval,
                rewrite_source=outcome.rewrite_source,
                rewrite_fallback=outcome.rewrite_fallback,
                rerank_fallback=outcome.rerank_fallback,
                latency_ms=latency_ms,
            )
        )
    return results


async def main() -> None:
    load_environment()
    os.environ.setdefault("LLM_MAX_RETRIES", "1")  # keep worst-case Claude calls low
    cases: list[dict[str, Any]] = json.loads(EVAL_PATH.read_text(encoding="utf-8"))

    budget = LlmCallBudget(
        Path(env_str("LLM_BUDGET_PATH", DEFAULT_BUDGET_PATH)),
        env_int("LLM_CALL_BUDGET", DEFAULT_LLM_CALL_BUDGET),
    )
    calls_before = budget.used()

    embedder = BgeEmbedder(env_str("EMBEDDING_MODEL", DEFAULT_EMBEDDING_MODEL))
    reranker = BgeReranker(env_str("RERANKER_MODEL", DEFAULT_RERANKER_MODEL))
    store = ChromaStore(chromadb.EphemeralClient(), f"benchmark-{uuid.uuid4().hex}")
    keyword_index = BM25Index()
    articles = ArticleService(embedder, store, keyword_index, asyncio.Lock())
    article_count = await seed(articles, Path(env_str("KB_DIR", "./data/kb")))

    rewriter, rewrite_provider = build_rewriter()
    candidates = env_int("CANDIDATES_PER_RETRIEVER", DEFAULT_CANDIDATES_PER_RETRIEVER)
    rrf_k = env_int("RRF_K", DEFAULT_RRF_K)
    rerank_candidates = env_int("RERANK_CANDIDATES", DEFAULT_RERANK_CANDIDATES)
    max_history = env_int("MAX_HISTORY_MESSAGES", DEFAULT_MAX_HISTORY_MESSAGES)
    rerank_min_score = env_float("RERANK_MIN_SCORE", DEFAULT_RERANK_MIN_SCORE)
    query_service = QueryService(rewriter, max_history_messages=max_history)
    service = SupportSearchService(
        query_service=query_service,
        retrieval_service=RetrievalService(
            embedder=embedder,
            vector_store=store,
            keyword_index=keyword_index,
            reranker=reranker,
            candidates_per_retriever=candidates,
            rrf_k=rrf_k,
            rerank_candidates=rerank_candidates,
            rerank_min_score=rerank_min_score,
        ),
        keyword_index=keyword_index,
    )

    # Warm up both models so the first timed case is not penalised.
    await service.search(
        SearchRequest(question="warm up", query_mode=QueryMode.QUESTION_ONLY, rerank=True)
    )

    results: list[CaseResult] = []
    for config in CONFIGS:
        config_results = await run_config(config, cases, service, query_service, rewriter)
        results.extend(config_results)
        retrieval_rows = [r for r in config_results if r.pattern != SMALL_TALK]
        print(
            f"{config.number}. {config.name:<26} hit@1={hit_at_k(retrieval_rows, 1):.2f} "
            f"hit@3={hit_at_k(retrieval_rows, 3):.2f} "
            f"mrr={mean_reciprocal_rank(retrieval_rows):.3f} llm_calls_total={budget.used()}"
        )

    meta = {
        "run_at": time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime()),
        "cases": len(cases),
        "retrieval_cases": sum(1 for c in cases if c["pattern"] != SMALL_TALK),
        "small_talk_cases": sum(1 for c in cases if c["pattern"] == SMALL_TALK),
        "articles": article_count,
        "chunks": keyword_index.size(),
        "embedding_model": embedder.model_name,
        "reranker_model": reranker.model_name,
        "rewrite_provider": rewrite_provider,
        "candidates": candidates,
        "rrf_k": rrf_k,
        "rerank_candidates": rerank_candidates,
        "max_history": max_history,
        "rerank_min_score": rerank_min_score,
        "llm_calls_this_run": budget.used() - calls_before,
        "llm_calls_total": budget.used(),
        "llm_call_budget": budget.limit,
    }
    write_report(render_tables(results, meta))
    RAW_RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    RAW_RESULTS_PATH.write_text(
        json.dumps({"meta": meta, "results": [r.__dict__ for r in results]}, indent=1),
        encoding="utf-8",
    )
    print(
        f"Wrote {REPORT_PATH.relative_to(PROJECT_ROOT)}. Claude calls this run: "
        f"{meta['llm_calls_this_run']}; total {meta['llm_calls_total']}/{budget.limit}."
    )


if __name__ == "__main__":
    asyncio.run(main())
