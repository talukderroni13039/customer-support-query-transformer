"""Benchmark: six pipeline configurations x the eval set -> docs/BENCHMARK.md.

Usage (PowerShell):  uv run python -m scripts.run_benchmark

- Uses the real embedding model, reranker, and BM25 on an in-memory copy of data/kb.
- Rewrites go through the rewrite cache (data/cache/rewrites.json), so only the first run
  calls Claude (one call per eval case that has history). Re-runs make zero API calls.
  Never delete the cache to re-run.
- Only the tables between the BENCHMARK markers are regenerated; the hand-written findings
  below them are preserved.
"""

